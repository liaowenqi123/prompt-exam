/** 随机抽 n 道题（默认 1 道） */
export function randomScenarios(n = 1) {
  const pool = [...SCENARIOS];
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, n);
}
